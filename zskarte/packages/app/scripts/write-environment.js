// Writes src/environments/environment.prod.ts from the build arguments ZSK_API_URL, ZSK_SEARCH_URL, ZSK_TILE_URL, ZSK_ORG_NAME and ZSK_CODE_LOGIN.
// Run before `ng build` (see Dockerfile.app). Without the variables the localhost defaults are used.
const fs = require('fs');
const path = require('path');

const target = path.join(__dirname, '..', 'src', 'environments', 'environment.prod.ts');
const value = (name, fallback) => process.env[name] || fallback;
// search label: "<organisation> (lokale Suche)", or "Lokale Suche" without an organisation name
const org = (process.env.ZSK_ORG_NAME || '').trim();
const searchLabel = org ? `${org} (lokale Suche)` : 'Lokale Suche';
// shown on the login page; same string as the service worker version (see scripts/update-ngsw-config.js)
const pkgVersion = require(path.join(__dirname, '..', 'package.json')).version;
const buildVersion = `${pkgVersion}-${process.env.COMMIT_SHA || 'unknown'}`;

// only the literal 'false' hides the code login, any other value (or none) keeps it
const codeLoginEnabled = value('ZSK_CODE_LOGIN', 'true') !== 'false';
const workLocalEnabled = value('ZSK_WORK_LOCAL', 'true') !== 'false';

const content = `// Generated by scripts/write-environment.js from ZSK_API_URL, ZSK_SEARCH_URL, ZSK_TILE_URL, ZSK_ORG_NAME, ZSK_CODE_LOGIN and ZSK_WORK_LOCAL. Do not edit by hand.

export const environment = {
  production: false,
  apiUrl: '${value('ZSK_API_URL', 'http://localhost:1337')}',
  tileUrl: '${value('ZSK_TILE_URL', 'http://localhost:8080/styles/osm-bright')}',
  searchUrl: '${value('ZSK_SEARCH_URL', 'http://localhost:8000/search/')}',
  searchLabel: '${searchLabel}',
  showNavLink: true,
  buildVersion: '${buildVersion}',
  appUrl: '${value('ZSK_APP_URL', 'http://localhost:4300')}',
  gitUrl: '${value('GIT_URL', '')}',
  codeLoginEnabled: ${codeLoginEnabled},
  workLocalEnabled: ${workLocalEnabled},
};
`;

fs.writeFileSync(target, content);
console.log(`environment.prod.ts written: apiUrl=${value('ZSK_API_URL', 'http://localhost:1337')}`);
