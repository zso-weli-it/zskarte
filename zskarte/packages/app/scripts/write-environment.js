// Writes src/environments/environment.prod.ts from the build arguments ZSK_API_URL, ZSK_SEARCH_URL, ZSK_TILE_URL, ZSK_ORG_NAME and ZSK_CODE_LOGIN.
// Run before `ng build` (see Dockerfile.app). Without the variables the localhost defaults are used.
const fs = require('fs');
const path = require('path');

// JSON encoding gives a valid TypeScript string literal, whatever quotes or backslashes the value holds
const literal = (value) => JSON.stringify(value);

const buildEnvironmentSource = (env) => {
  const value = (name, fallback) => env[name] || fallback;
  // search label: "<organisation> (lokale Suche)", or "Lokale Suche" without an organisation name
  const org = (env.ZSK_ORG_NAME || '').trim();
  const searchLabel = org ? `${org} (lokale Suche)` : 'Lokale Suche';
  // shown on the login page; same string as the service worker version (see scripts/update-ngsw-config.js)
  const pkgVersion = require(path.join(__dirname, '..', 'package.json')).version;
  const buildVersion = `${pkgVersion}-${env.COMMIT_SHA || 'unknown'}`;

  // only the literal 'false' hides the code login, any other value (or none) keeps it
  const codeLoginEnabled = value('ZSK_CODE_LOGIN', 'true') !== 'false';
  const workLocalEnabled = value('ZSK_WORK_LOCAL', 'true') !== 'false';

  return `// Generated by scripts/write-environment.js from ZSK_API_URL, ZSK_SEARCH_URL, ZSK_TILE_URL, ZSK_ORG_NAME, ZSK_CODE_LOGIN and ZSK_WORK_LOCAL. Do not edit by hand.

export const environment = {
  production: false,
  apiUrl: ${literal(value('ZSK_API_URL', 'http://localhost:1337'))},
  tileUrl: ${literal(value('ZSK_TILE_URL', 'http://localhost:8080/styles/osm-bright'))},
  searchUrl: ${literal(value('ZSK_SEARCH_URL', 'http://localhost:8000/search/'))},
  searchLabel: ${literal(searchLabel)},
  showNavLink: true,
  buildVersion: ${literal(buildVersion)},
  appUrl: ${literal(value('ZSK_APP_URL', 'http://localhost:4300'))},
  gitUrl: ${literal(value('GIT_URL', ''))},
  codeLoginEnabled: ${codeLoginEnabled},
  workLocalEnabled: ${workLocalEnabled},
};
`;
};

module.exports = { buildEnvironmentSource };

if (require.main === module) {
  const target = path.join(__dirname, '..', 'src', 'environments', 'environment.prod.ts');
  fs.writeFileSync(target, buildEnvironmentSource(process.env));
  console.log(`environment.prod.ts written: apiUrl=${process.env.ZSK_API_URL || 'http://localhost:1337'}`);
}
