// Writes src/environments/environment.prod.ts from the build arguments ZSK_API_URL, ZSK_SEARCH_URL, ZSK_TILE_URL and ZSK_SEARCH_LABEL.
// Run before `ng build` (see Dockerfile.app). Without the variables the localhost defaults are used.
const fs = require('fs');
const path = require('path');

const target = path.join(__dirname, '..', 'src', 'environments', 'environment.prod.ts');
const value = (name, fallback) => process.env[name] || fallback;

const content = `// Generated by scripts/write-environment.js from ZSK_API_URL, ZSK_SEARCH_URL, ZSK_TILE_URL and ZSK_SEARCH_LABEL. Do not edit by hand.

export const environment = {
  production: false,
  apiUrl: '${value('ZSK_API_URL', 'http://localhost:1337')}',
  tileUrl: '${value('ZSK_TILE_URL', 'http://localhost:8080/styles/osm-bright')}',
  searchUrl: '${value('ZSK_SEARCH_URL', 'http://localhost:8000/search/')}',
  searchLabel: '${value('ZSK_SEARCH_LABEL', 'Lokale Suche')}',
  showNavLink: true,
};
`;

fs.writeFileSync(target, content);
console.log(`environment.prod.ts written: apiUrl=${value('ZSK_API_URL', 'http://localhost:1337')}`);
